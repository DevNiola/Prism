/// Analyzes a sequence of [`DiagnosticEvent`] objects and reconstructs the
/// contract call chain at the point of first failure.
///
/// The analyzer is stateless; create a new instance with [`ChainAnalyzer::new`]
/// and call [`ChainAnalyzer::analyze`] as many times as needed.
pub struct ChainAnalyzer;

impl ChainAnalyzer {
    /// Create a new analyzer instance.
    pub fn new() -> Self {
        Self
    }

    /// Analyze `events` and return the reconstructed [`CallChain`], or `None`
    /// when the event sequence contains no failure indicators.
    ///
    /// The algorithm iterates the events exactly once (O(n)) and never
    /// re-visits events, so it is safe to call on arbitrarily long sequences
    /// without risk of infinite loops.
    pub fn analyze(&self, events: &[DiagnosticEvent]) -> Option<CallChain> {
        let mut stack: Vec<StackFrame> = Vec::new();

        for event in events {
            let ContractEventBody::V0(v0) = &event.event.body;

            let topics: Vec<String> = v0.topics.iter().filter_map(topic_to_string).collect();

            let first_topic = topics.first().map(String::as_str);

            // ----------------------------------------------------------------
            // Maintain the call stack
            // ----------------------------------------------------------------
            match first_topic {
                Some("fn_call") => {
                    let address = match &event.event.contract_id {
                        Some(hash) => hash_to_strkey(hash),
                        // Host-level fn_call events sometimes lack a contract_id;
                        // use the second topic (callee address hint) as a fallback.
                        None => topics
                            .get(1)
                            .cloned()
                            .unwrap_or_else(|| "<unknown>".to_string()),
                    };
                    // The function name is the second topic for fn_call events
                    // (first topic = "fn_call", second = function name).
                    let function_name = topics.get(1).cloned();
                    stack.push(StackFrame {
                        contract_address: address,
                        function_name,
                        depth: stack.len(),
                    });
                    continue;
                }
                Some("fn_return") => {
                    stack.pop();
                    continue;
                }
                _ => {}
            }

            // ----------------------------------------------------------------
            // Detect failure
            // ----------------------------------------------------------------
            if is_failure(event, &topics, &v0.data) {
                let mut chain = Self::build_chain(&stack, event);
                let patterns = Self::detect_patterns(events, &chain);
                if !patterns.is_empty() {
                    let names: Vec<&str> = patterns.iter().map(|p| p.pattern_name.as_str()).collect();
                    chain.summary.push_str(&format!("  |  Failure patterns: {}", names.join(", ")));
                    chain.pattern_matches = patterns;
                }
                return Some(chain);
            }
        }

        None
    }

    /// Detect common failure patterns from diagnostic events and the call chain.
    pub fn detect_patterns(events: &[DiagnosticEvent], chain: &CallChain) -> Vec<FailurePatternMatch> {
        let mut matches = Vec::new();
        let mut all_topics = Vec::new();
        let mut all_text = String::new();

        for ev in events {
            if let ContractEventBody::V0(v0) = &ev.event.body {
                for t in &v0.topics {
                    if let Some(s) = topic_to_string(t) {
                        all_topics.push(s.to_lowercase());
                    }
                }
                all_text.push_str(&format!(" {:?} ", v0.data).to_lowercase());
            }
        }
        let topics_str = all_topics.join(" ");
        let full_text = format!("{} {}", topics_str, all_text);

        // Pattern 1: Insufficient balance + auth failure
        let has_balance = full_text.contains("balance") || full_text.contains("underfunded") || full_text.contains("insufficient");
        let has_auth = full_text.contains("auth") || full_text.contains("signature") || full_text.contains("unauthorized");
        if has_balance && has_auth {
            matches.push(FailurePatternMatch {
                pattern_name: "InsufficientBalanceWithAuthFailure".to_string(),
                description: "Insufficient balance combined with authorization failure".to_string(),
                explanation: "The transaction failed during authorization while operating on an account with insufficient balance or uninitialized reserves.".to_string(),
                confidence: "High".to_string(),
                detected_indicators: vec![
                    "Detected authorization failure event".to_string(),
                    "Detected insufficient balance error indicator".to_string(),
                ],
                suggested_fixes: vec![
                    "Verify the source account has sufficient available XLM and token reserves prior to signing.".to_string(),
                    "Ensure contract authorizations and account trustlines are in place before transaction submission.".to_string(),
                ],
            });
        }

        // Pattern 2: Budget exceeded + large storage read
        let has_budget = full_text.contains("budget") || full_text.contains("cpu_limit") || full_text.contains("insns") || full_text.contains("mem_bytes");
        let has_storage = full_text.contains("storage") || full_text.contains("read") || full_text.contains("ledger_entry");
        if has_budget && has_storage {
            matches.push(FailurePatternMatch {
                pattern_name: "BudgetExceededWithLargeStorageRead".to_string(),
                description: "Budget limit exceeded during heavy storage read operations".to_string(),
                explanation: "The Soroban budget was exhausted while loading or querying contract storage entries.".to_string(),
                confidence: "High".to_string(),
                detected_indicators: vec![
                    "Detected budget limit exhaustion indicator".to_string(),
                    "Detected storage read / footprint access".to_string(),
                ],
                suggested_fixes: vec![
                    "Increase the transaction CPU instruction limit in SorobanResources.".to_string(),
                    "Break large contract storage queries into paginated batches to reduce single-invocation resource consumption.".to_string(),
                ],
            });
        }

        // Pattern 3: Expired ledger entry / TTL
        let has_expired = full_text.contains("expired") || full_text.contains("ttl") || full_text.contains("liveto");
        if has_expired {
            matches.push(FailurePatternMatch {
                pattern_name: "ExpiredStorageEntryAccess".to_string(),
                description: "Attempted access to an expired contract storage entry".to_string(),
                explanation: "The contract attempted to read or modify a storage entry whose Time-To-Live (TTL) has passed.".to_string(),
                confidence: "High".to_string(),
                detected_indicators: vec![
                    "Detected storage TTL expiration event".to_string(),
                ],
                suggested_fixes: vec![
                    "Submit an ExtendFootprintTTL operation to restore and prolong the entry lifetime.".to_string(),
                    "Ensure rent bump operations are triggered before entry expiration.".to_string(),
                ],
            });
        }

        // Pattern 4: Deep recursion / call depth
        if chain.frames.len() >= 4 {
            matches.push(FailurePatternMatch {
                pattern_name: "DeepRecursionOrCascadeFailure".to_string(),
                description: "Call stack exceeded safe recursion threshold before failing".to_string(),
                explanation: format!("The transaction reached a call stack depth of {} contracts, indicating an unconstrained recursion loop or cascade.", chain.frames.len()),
                confidence: "Medium".to_string(),
                detected_indicators: vec![
                    format!("Call depth reached {} frames", chain.frames.len()),
                ],
                suggested_fixes: vec![
                    "Inspect the contract invocation graph to remove cyclic or recursive cross-contract calls.".to_string(),
                    "Implement a reentrancy guard or maximum call depth check in contract logic.".to_string(),
                ],
            });
        }

        matches
    }

    // -----------------------------------------------------------------------
    // Private helpers
    // -----------------------------------------------------------------------

    /// Assemble a [`CallChain`] from the current stack snapshot and the event
    /// that triggered the failure detection.
    fn build_chain(stack: &[StackFrame], failing_event: &DiagnosticEvent) -> CallChain {
        if stack.is_empty() {
            // Failure occurred before any fn_call was seen - synthesize a
            // single-frame chain from the event's own contract_id.
            let address = failing_event
                .event
                .contract_id
                .as_ref()
                .map_or_else(|| "<unknown>".to_string(), hash_to_strkey);

            let frame = ChainFrame {
                contract_address: address.clone(),
                function_name: None,
                depth: 0,
                is_error_frame: true,
                role: FrameRole::RootCause,
            };
            let summary = format!("Root cause: {address} (no call chain captured)");
            let chain = CallChain {
                frames: vec![frame],
                root_cause_index: Some(0),
                trace: String::new(), // filled below
                summary,
                pattern_matches: Vec::new(),
            };
            return Self::finalize(chain);
        }

        // The deepest frame (innermost) is the root cause; everything above it
        // in the stack is a fault-line frame.
        let root_cause_index = stack.len().saturating_sub(1);

        let frames: Vec<ChainFrame> = stack
            .iter()
            .enumerate()
            .map(|(i, sf)| {
                let role = if i == root_cause_index {
                    FrameRole::RootCause
                } else {
                    FrameRole::FaultLine
                };
                ChainFrame {
                    contract_address: sf.contract_address.clone(),
                    function_name: sf.function_name.clone(),
                    depth: sf.depth,
                    is_error_frame: i == root_cause_index,
                    role,
                }
            })
            .collect();

        let root_frame = &frames[root_cause_index];
        let summary = format!(
            "Root cause: {}  |  Fault line: {} contract(s) affected",
            root_frame.label(),
            frames.len().saturating_sub(1),
        );

        let chain = CallChain {
            frames,
            root_cause_index: Some(root_cause_index),
            trace: String::new(), // filled by finalize
            summary,
            pattern_matches: Vec::new(),
        };
        Self::finalize(chain)
    }

    /// Populate the `trace` field by calling `render_trace` on the chain.
    fn finalize(mut chain: CallChain) -> CallChain {
        chain.trace = chain.render_trace();
        chain
    }
}

// ---------------------------------------------------------------------------
// Shared helpers
// ---------------------------------------------------------------------------
//
// These were originally private methods on `ChainAnalyzer`. They are now
// crate-visible free functions so that `deepest_error::DeepestErrorFinder`
// (which needs the exact same call-stack tracking and failure-detection
// logic to walk the full event cascade) can reuse them without duplicating
// the logic.

/// Extract a string representation of an `ScVal` topic.
pub(crate) fn topic_to_string(val: &ScVal) -> Option<String> {
    match val {
        ScVal::Symbol(sym) => Some(sym.to_string()),
        ScVal::String(s) => Some(s.to_string()),
        _ => None,
    }
}

/// Returns `true` when an event is considered a failure indicator.
pub(crate) fn is_failure(event: &DiagnosticEvent, topics: &[String], data: &ScVal) -> bool {
    // The host sets this flag to false for every event inside a failing frame.
    if !event.in_successful_contract_call {
        return true;
    }

    // An ScVal::Error payload always signals a contract-level error.
    if matches!(data, ScVal::Error(_)) {
        return true;
    }

    // Well-known failure topic keywords.
    topics.iter().any(|t| {
        let lower = t.to_ascii_lowercase();
        lower == "error"
            || lower == "panic"
            || lower == "revert"
            || lower == "hosterror"
            || lower.contains("failed")
            || lower.contains("trap")
    })
}

/// Encode a 32-byte hash as a Stellar contract strkey (`C...`).
pub(crate) fn hash_to_strkey(hash: &Hash) -> String {
    StrkeyContract(hash.0).to_string()
}

impl Default for ChainAnalyzer {
    fn default() -> Self {
        Self::new()
    }
}

// ---------------------------------------------------------------------------
// Convenience free function
// ---------------------------------------------------------------------------

/// Analyze `events` with a default [`ChainAnalyzer`] and return the
/// reconstructed [`CallChain`], or `None` if no failure was detected.
pub fn analyze_call_chain(events: &[DiagnosticEvent]) -> Option<CallChain> {
    ChainAnalyzer::new().analyze(events)
}

